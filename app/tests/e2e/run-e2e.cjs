/**
 * run-e2e.cjs — runs every tests/e2e/e2e-*.cjs sequentially and reports a
 * pass/fail summary with a non-zero exit code on any failure.
 *
 * These are hand-written Playwright-driven Electron scripts (not a
 * `playwright test` project — there is no playwright.config.ts), each
 * exercising one real user flow against the built app via window.api. Every
 * script already exits non-zero / throws on assertion failure, so this
 * runner's only job is sequencing + a summary (mirrors
 * tests/r-validation/run-all.R's role for the R suite).
 *
 * Prerequisites (not automated here):
 *   1. `pnpm build` (scripts spawn out/main/main.cjs directly)
 *   2. `node tests/e2e/setup-e2e-fixtures.cjs` — writes the shared /tmp/sai-*.csv
 *      files. Without them ~30 scripts fail with DuckDB's "No files found that
 *      match the pattern", which reads like a product bug and is not one. A
 *      few scripts build their own fixture and need nothing; the very large
 *      ones (sai-e2e-200000.csv, sai-colwidth-50k.csv, sai-chunked-*.csv,
 *      sai-move-col-50k.csv, sai-autoscroll-200.csv) and the binary ones
 *      (sai-cell-format-test.sdf, sai-numeric-reject.png) are generated by
 *      their own script or must be produced by hand — see each script's header.
 *   3. R with the packages the exercised analyses need. A vendored runtime
 *      under resources/ (r-runtime-win, r-runtime-mac, r-runtime) is found on
 *      its own (r-bridge.ts); otherwise Rscript must be on PATH.
 *   4. On Linux without a display: run under `xvfb-run -a`
 *   5. `ELECTRON_RUN_AS_NODE` must be genuinely unset — see the env handling
 *      below for why an empty string is not enough.
 *
 * Usage: node tests/e2e/run-e2e.cjs [pattern]
 *   pattern (optional): only run scripts whose filename includes this substring.
 */
const { spawnSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const scriptsDir = __dirname
// Scripts resolve out/main/main.cjs, tmp/ and fixtures relative to app/.
const appDir = path.join(scriptsDir, '..', '..')
const mainEntry = path.join('out', 'main', 'main.cjs')
const pattern = process.argv[2]

/**
 * Kill Electron instances of this app left behind by the previous script.
 * spawnSync's timeout SIGKILLs the script's node process only; the Electron
 * child it launched survives, keeps the app's single-instance lock
 * (main.ts requestSingleInstanceLock) and every later launch quits on
 * start-up — one timeout turned ~80 later scripts into "Target page,
 * context or browser has been closed" in CI.
 */
function killStrayElectron() {
  if (process.platform === 'win32') {
    spawnSync(
      'powershell',
      [
        '-NoProfile',
        '-Command',
        'Get-CimInstance Win32_Process -Filter "Name=\'electron.exe\'" | ' +
          "Where-Object { $_.CommandLine -like '*out*main*main.cjs*' } | " +
          'ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }'
      ],
      { stdio: 'ignore' }
    )
  } else {
    spawnSync('pkill', ['-KILL', '-f', mainEntry], { stdio: 'ignore' })
  }
}

const files = fs
  .readdirSync(scriptsDir)
  .filter(f => f.startsWith('e2e-') && f.endsWith('.cjs'))
  .filter(f => !pattern || f.includes(pattern))
  .sort()

if (files.length === 0) {
  console.error(`No e2e-*.cjs scripts found${pattern ? ` matching "${pattern}"` : ''}.`)
  process.exit(1)
}

// Per-script wall clock. Without it a single hung script blocks the whole
// suite indefinitely — e2e-output-navigator was still sitting there after 63
// minutes and had to be killed by hand, which is indistinguishable from "the
// suite is just slow" and makes `pnpm test:e2e` unusable. Override with
// SAI_E2E_TIMEOUT_MS for the genuinely long large-fixture scripts.
const TIMEOUT_MS = Number(process.env.SAI_E2E_TIMEOUT_MS) || 300000

// Scripts that are long by design get their own limit (never lower than
// TIMEOUT_MS). Measured on Windows, 2026-10-24: paste-syntax runs 78 dialogs
// twice each (Paste → Run, then OK) in 439 s; dialog-prefill 664 s. Limits are
// about twice that, so a slower CI runner still finishes but a real hang does
// not run forever.
const LONG_SCRIPT_TIMEOUT_MS = {
  'e2e-paste-syntax.cjs': 900000,
  'e2e-dialog-prefill.cjs': 1200000
}
const timeoutFor = file => Math.max(TIMEOUT_MS, LONG_SCRIPT_TIMEOUT_MS[file] ?? 0)

console.log(`Running ${files.length} e2e script(s)... (timeout ${TIMEOUT_MS / 1000}s each)\n`)

const results = []
for (const file of files) {
  const full = path.join(scriptsDir, file)
  const timeout = timeoutFor(file)
  process.stdout.write(`--- ${file} --- `)
  const { status, signal, error } = spawnSync('node', [full], {
    cwd: appDir,
    stdio: 'inherit',
    timeout,
    killSignal: 'SIGKILL',
    // ELECTRON_RUN_AS_NODE must be genuinely ABSENT, not empty. Electron's
    // native launcher tests it with getenv(), which returns "" (a non-NULL
    // pointer) for a variable set to the empty string — so `: ''` still puts
    // Electron in Node mode, no window is ever created, and every script dies
    // with Playwright's opaque "Process failed to launch!". Delete the key.
    env: (() => {
      const e = { ...process.env }
      delete e.ELECTRON_RUN_AS_NODE
      // The start-up Welcome dialog is a full-window overlay that would
      // swallow every script's clicks; e2e-welcome.cjs opts back in itself.
      e.SAI_NO_WELCOME = '1'
      // Main only honors renderer-supplied file paths without a dialog/drop under this flag
      // (and never in a packaged build — electron/ipc/approved-paths.ts).
      e.SAI_E2E = '1'
      return e
    })()
  })
  // spawnSync reports a timeout as error.code ETIMEDOUT (and the kill signal),
  // so call it out by name instead of leaving a bare "signal=SIGKILL".
  const timedOut = error && error.code === 'ETIMEDOUT'
  const passed = status === 0 && !signal && !error
  killStrayElectron()
  results.push({ file, passed, status, signal, timedOut })
  if (passed) console.log(`\n${file}: PASS`)
  else if (timedOut) console.log(`\n${file}: TIMEOUT (>${timeout / 1000}s, killed)`)
  else console.log(`\n${file}: FAIL (status=${status}, signal=${signal})`)
}

const failed = results.filter(r => !r.passed)
console.log(`\n${results.length - failed.length}/${results.length} e2e scripts passed.`)
if (failed.length > 0) {
  console.log('\nFailed:')
  failed.forEach(r => console.log(`  - ${r.file}`))
  process.exit(1)
}
